import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
const get=p=>readFileSync(p,"utf8")

test("God diagnostics run only as signed verified owner; token never reaches browser",()=>{
 const worker=get("modern/src/api/worker.ts")
 assert.ok(worker.includes('app.get("/api/v1/god/diagnostics"'))
 assert.ok(worker.includes('db.auth.getClaims(match[1])'))
 assert.ok(worker.includes('db.rpc("upt_current_session_context")'))
 assert.ok(worker.includes('if(!actor.identity.is_owner)'))
 assert.ok(worker.includes('rpc("upt_current_is_owner")'))
 assert.ok(worker.includes('rpc("upt_god_login_owner")'))
 assert.ok(worker.includes('rpc("upt_god_maker_log_snapshot"'))
 assert.ok(worker.includes('rpc("upt_god_logout"'))
 assert.ok(worker.indexOf('rpc("upt_god_logout"')>worker.indexOf("}finally{"))
 assert.ok(!worker.includes('token_hash'))
 assert.ok(!worker.includes('stack_trace'))
 assert.ok(!worker.includes('client_context'))
 const screen=get("modern/src/screens/maker-diagnostics.tsx")
 assert.ok(screen.includes('protectedCandidateGet<Diagnostics>("/api/v1/god/diagnostics")'))
 assert.ok(!screen.includes("upt_god_login_owner"))
 assert.ok(!screen.includes("localStorage"))
 const main=get("modern/src/main.tsx")
 assert.ok(main.includes("<MakerGuard>"))
 assert.ok(main.includes("identity?.is_owner"))
 assert.ok(main.includes('path="/god/*" element={<Missing/>}'))
})
test("Business integration metadata is accessible only after separate organization permissions",()=>{
 const worker=get("modern/src/api/worker.ts")
 assert.ok(worker.includes('app.get("/api/v1/integrations/status"'))
 assert.ok(worker.includes('db.rpc("upt_can_manage_integrations")'))
 assert.ok(worker.includes('actor.db.rpc("upt_integration_credentials",{p_action:"list"})'))
 assert.ok(worker.includes('if(allowed!==true)'))
 assert.ok(!worker.includes('p_action:"read"'))
 assert.ok(!worker.includes('p_action:"save"'))
 assert.ok(!worker.includes('p_action:"disconnect"'))
 assert.ok(!worker.includes("WEEZTIX_CLIENT_SECRET"))
 assert.ok(!worker.includes("SUMUP_OAUTH_ACCESS_TOKEN"))
 const status=get("modern/src/components/integration-status.tsx")
 assert.ok(status.includes('protectedCandidateGet<Status>("/api/v1/integrations/status")'))
 assert.ok(status.includes("Geen API-sleutels of tokens"))
 const admin=get("modern/src/screens/administration.tsx")
 for(const area of ["invoices","banking","ticketing","contracts"])
  assert.ok(admin.includes('area="'+area+'"'))
 assert.ok(!get("modern/src/main.tsx").includes('path="/integrations"'))
})
test("session refresh is generation-scoped and always revalidates live access on resume",()=>{
 const session=get("modern/src/lib/session.tsx")
 assert.ok(session.includes("const generation=useRef(0)"))
 assert.ok(session.includes("const ticket=++generation.current"))
 assert.ok((session.match(/if\(ticket!==generation.current\)return/g)||[]).length>=3)
 assert.ok(session.includes('document.addEventListener("visibilitychange",visible)'))
 assert.ok(session.includes('document.removeEventListener("visibilitychange",visible)'))
 assert.ok(session.includes('setState({status:"checking",identity:null,portals:[]})'))
 assert.ok(session.includes("++generation.current"))
 assert.ok(session.includes("purgeLocalUser(lastIdentity.current)"))
})
