import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
const read=(path)=>readFileSync(new URL("../"+path,import.meta.url),"utf8")

test("promotion messages preserve existing room RLS and gain guarded same-room replies",()=>{
 const migration=read("supabase/migrations/20261109134038_promotion_chat_replies_read_receipts.sql")
 assert.match(migration,/alter table public\.promotion_chat_messages/)
 assert.match(migration,/reply_to_message_id uuid/)
 assert.match(migration,/previous\.room=new\.room/)
 assert.match(migration,/before insert on public\.promotion_chat_messages/)
 assert.doesNotMatch(migration,/drop table.*promotion_chat_messages/i)
 assert.doesNotMatch(migration,/drop policy.*promotion_chat_read/i)
})
test("promotion read state is private and scoped to an approved portal account",()=>{
 const migration=read("supabase/migrations/20261109134038_promotion_chat_replies_read_receipts.sql")
 assert.match(migration,/create table if not exists upt_private\.promotion_chat_read_states/)
 assert.match(migration,/alter table upt_private\.promotion_chat_read_states enable row level security/)
 assert.match(migration,/revoke all on upt_private\.promotion_chat_read_states from public,anon,authenticated/)
 for(const fn of ["upt_promotion_chat_mark_read","upt_promotion_chat_unread_counts","upt_promotion_chat_readers"]){
  assert.ok(migration.includes("public."+fn),fn)
  assert.match(migration,new RegExp("revoke all on function public\\."+fn+"\\([^)]*\\) from public,anon"))
  assert.match(migration,new RegExp("grant execute on function public\\."+fn+"\\([^)]*\\) to authenticated"))
 }
 assert.match(migration,/not public\.upt_promotion_chat_allowed\(\)/)
 assert.match(migration,/d\.portal_label='promotion'/)
})
