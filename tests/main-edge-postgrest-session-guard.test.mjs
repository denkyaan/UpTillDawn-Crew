import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const middleware=readFileSync('lib/supabase/middleware.ts','utf8')
const layout=readFileSync('app/(app)/layout.tsx','utf8')
const serverUser=readFileSync('lib/actions/auth.ts','utf8')
const dbMigration=readFileSync('supabase/migrations/20261117175500_single_verified_session_context.sql','utf8')

test('ordinary authenticated pages rely on signed, user-scoped PostgREST auth, never only cookie presence',()=>{
 assert.match(layout,/await getCurrentUser\(\)/)
 assert.match(layout,/if \(!current\) redirect\('\/login'\)/)
 assert.match(serverUser,/await readContext\('upt_current_session_context'\)/)
 assert.match(serverUser,/if \(error \|\| !profile \|\| !profile\.id/)
 assert.match(serverUser,/if \(profile\.account_blocked && !isOwner\) return null/)
 assert.match(serverUser,/if \(!profile\.approved && !isOwner\) return null/)
 assert.match(dbMigration,/security invoker/)
 assert.match(dbMigration,/where p\.id=auth\.uid\(\)/)
 assert.match(dbMigration,/grant execute on function public\.upt_current_session_context\(\) to authenticated/)
 assert.match(dbMigration,/revoke execute on function public\.upt_current_session_context\(\) from public, anon/)
})
test('only protected (app) PAGE paths may skip redundant edge JWT work',()=>{
 assert.match(middleware,/const ordinaryAppPage = pathname === '\/'/)
 assert.match(middleware,/pathname\.startsWith\('\/portals\/promotion\/'\)/)
 assert.match(middleware,/pathname\.startsWith\('\/portals\/administration\/'\)/)
 assert.match(middleware,/pathname === '\/portals'/)
 assert.match(middleware,/const safeRead = request\.method === 'GET' \|\| request\.method === 'HEAD'/)
 assert.match(middleware,/safeRead && ordinaryAppPage && !requiresEarlyRoleCheck && !routeHandlerWithoutAppLayout/)
 assert.match(middleware,/return NextResponse\.next\(\{ request \}\)/)
 const pageRoots=middleware.slice(middleware.indexOf('const appPageRoots = ['),middleware.indexOf('const ordinaryAppPage ='))
 assert.doesNotMatch(pageRoots,/god-mode|maker-mode|\/admin|\/api/)
})
test('Maker, Admin, Finance, route handlers and normal auth pages keep edge verified claims',()=>{
 assert.match(middleware,/const requiresEarlyRoleCheck =[\s\S]*?pathname === '\/admin'/)
 assert.match(middleware,/pathname\.startsWith\('\/admin\/'\)/)
 assert.match(middleware,/pathname === '\/portals\/administration\/finance'/)
 assert.match(middleware,/pathname\.startsWith\('\/portals\/administration\/finance\/'\)/)
 assert.match(middleware,/pathname\.startsWith\('\/portals\/switch\/'\)/)
 assert.match(middleware,/agreement\\\/\(\?:archive\|print\)/)
 assert.match(middleware,/const \{ data: verified, error: claimsError \} = await supabase\.auth\.getClaims\(\)/)
 assert.match(middleware,/const makerRoute = pathname === '\/maker-mode'/)
 assert.match(middleware,/if \(!hasSessionCookie\)/)
 assert.match(middleware,/if \(authenticated && makerRoute\)/)
 assert.match(middleware,/if \(authenticated && \(isAdminArea \|\| isFinanceArea\)\)/)
})
