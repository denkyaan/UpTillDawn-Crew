import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
import {isSupportedLocalOcrLanguage,recognizeLocally} from "../lib/administration/local-document-ocr.ts"

const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8")

test("local OCR refuses malformed or mismatched inputs before any browser assets or provider requests",async()=>{
 for(const code of ["nld","fra","eng","deu"])assert.equal(isSupportedLocalOcrLanguage(code),true)
 for(const code of ["","NLD","ita",null,"eng,../../"])assert.equal(isSupportedLocalOcrLanguage(code),false)
 const invalid=new File([new Uint8Array(12)],"invoice.png",{type:"image/png"})
 await assert.rejects(recognizeLocally(invalid,"eng"),/local_ocr_unsupported_file/)
 const wrongType=new File([new TextEncoder().encode("%PDF-1.7\nABCDEFG")],"invoice.png",{type:"image/png"})
 await assert.rejects(recognizeLocally(wrongType,"eng"),/local_ocr_unsupported_file/)
 const tooBig=new File([new Uint8Array(5*1024*1024+1)],"invoice.png",{type:"image/png"})
 await assert.rejects(recognizeLocally(tooBig,"eng"),/local_ocr_invalid_file/)
 await assert.rejects(recognizeLocally(invalid,"ita"),/local_ocr_invalid_language/)
})

test("default finance OCR is local; no app key or upload endpoint is needed",()=>{
 const page=read("app/(app)/portals/administration/finance/page.tsx")
 const panel=read("components/administration/local-document-ocr-preview.tsx")
 const engine=read("lib/administration/local-document-ocr.ts")
 assert.match(page,/import LocalDocumentOcrPreview/)
 assert.equal((page.match(/<LocalDocumentOcrPreview locale=\{locale\}\/>/g)||[]).length,1)
 assert.doesNotMatch(page,/import CloudmersiveOcrPreview|<CloudmersiveOcrPreview/)
 assert.match(page,/<InvoiceLineCsvImport/)
 assert.match(panel,/recognizeLocally\(/)
 assert.match(panel,/data-no-translate/)
 assert.match(panel,/result\.text/)
 assert.doesNotMatch(panel,/fetch\s*\(|CLOUDMERSIVE_OCR_API_KEY|CloudmersiveOcrPreview/)
 assert.doesNotMatch(engine,/api\.cloudmersive\.com|CLOUDMERSIVE_OCR_API_KEY|NEXT_PUBLIC_CLOUDMERSIVE/)
 assert.match(engine,/await worker\.recognize\(file\)/)
 assert.match(engine,/await worker\.recognize\(canvas\)/)
 assert.match(engine,/page\.getTextContent\(\)/)
 assert.match(engine,/document\.numPages>maxPages/)
 assert.match(engine,/await worker\.terminate\(\)/)
 assert.match(engine,/isEvalSupported:false/)
 assert.match(engine,/const asset="\/vendor\/ocr"/)
 for(const locale of ["nl:","fr:","en:","de:"])assert.ok(panel.includes(locale),locale)
})

test("local OCR ships pinned worker/WASM/PDF/language assets on same-origin and caches for offline reuse",()=>{
 const build=read("scripts/prepare-local-ocr.mjs")
 const pkg=JSON.parse(read("package.json"))
 const sw=read("public/sw.js")
 const deploy=read(".github/workflows/deploy-main.yml")
 assert.match(build,/tesseract\.js@7\.0\.0/)
 assert.match(build,/tesseract\.js-core@7\.0\.0/)
 assert.match(build,/pdfjs-dist@5\.4\.149/)
 assert.match(build,/4\.0\.0_fast/)
 for(const language of ["nld","fra","eng","deu"])assert.ok(build.includes('"'+language+'"'),language)
 assert.match(build,/\.traineddata\.gz/)
 assert.match(build,/Unexpected asset size/)
 assert.match(build,/Invalid WASM header/)
 assert.match(build,/Invalid gzipped model/)
 assert.match(pkg.scripts["build:cloudflare"],/prepare-local-ocr\.mjs/)
 assert.match(pkg.scripts.prebuild,/prepare-local-ocr\.mjs/)
 assert.match(sw,/LOCAL_OCR_CACHE/)
 assert.match(sw,/url\.pathname\.startsWith\('\/vendor\/ocr\/'\)/)
 assert.match(sw,/cache\.put\(event\.request,response\.clone\(\)\)/)
 assert.match(deploy,/Verify self-hosted OCR assets built for main/)
 assert.match(deploy,/Verify local-first OCR assets are reachable on main/)
 assert.match(deploy,/vars\.ENABLE_CLOUDMERSIVE_OCR_TEST == 'true'/)
})
