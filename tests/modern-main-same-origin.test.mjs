import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
const read=p=>readFileSync(p,"utf8")
test("new lightweight Main is mounted at /modern without cutting over legacy or production",()=>{
 const next=read("next.config.mjs")
 assert.ok(next.includes("process.env.NEXT_PUBLIC_APP_URL === 'https://uptilldawn-main.uptilldawn.workers.dev'"))
 assert.ok(next.includes("source: '/modern/:path*', destination: '/modern/index.html'"))
 assert.ok(next.includes("fallback:"))
 assert.ok(!read(".github/workflows/deploy-cloudflare.yml").includes("modern/wrangler.main-qa"))
 const workflow=read(".github/workflows/deploy-main.yml")
 assert.ok(workflow.includes("npm --prefix modern run build -- --base=/modern/ --outDir=../public/modern"))
 assert.ok(workflow.includes("node scripts/main-modern-same-origin-smoke.mjs"))
 const dashboard=read("app/(app)/page.tsx")
 assert.ok(dashboard.includes('<a href="/modern"'))
 const proxy=read("proxy.ts")
 assert.ok(proxy.includes("modern(?:/|$)"))
})
test("same-origin React routes are isolated and never replace the old PWA service worker",()=>{
 const entry=read("modern/src/main.tsx")
 assert.ok(entry.includes('basename={sameOriginMount?"/modern":undefined}'))
 assert.ok(entry.includes('!sameOriginMount&&"serviceWorker" in navigator'))
 assert.ok(entry.includes('const legacyMainUrl="https://uptilldawn-main.uptilldawn.workers.dev"'))
})
test("Main only Hono proxy is read-only, no cookies, exact allowlist, no production",()=>{
 const api=read("app/api/v1/[...path]/route.ts")
 assert.ok(api.includes("export async function GET("))
 assert.ok(api.includes("process.env.NEXT_PUBLIC_APP_URL!==MAIN_ORIGIN"))
 assert.ok(api.includes("READ_ONLY_ENDPOINTS.has(endpoint)"))
 assert.ok(api.includes("'health', 'session', 'god/diagnostics', 'integrations/status'"))
 assert.ok(api.includes("'Authorization':authorization"))
 assert.ok(!api.includes("request.headers.get('cookie')"))
 assert.ok(!api.includes("process.env.SUPABASE_SERVICE_ROLE_KEY"))
 assert.ok(!api.includes("export async function POST"))
 const smoke=read("scripts/main-modern-same-origin-smoke.mjs")
 for(const path of ["/modern","/modern/login","/api/v1/health","/api/v1/session","/login/admin"])
  assert.ok(smoke.includes(path))
 assert.ok(smoke.includes("writeOperationsAttempted:0"))
})
