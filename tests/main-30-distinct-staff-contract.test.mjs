test('workflow runs after existing Main functional and browser QA, cleans even on failure and never triggers production',()=>{
 const job=workflow.slice(workflow.indexOf('  qa-main-concurrency-acceptance:'),workflow.indexOf('  qa-main-runtime-diagnostic:'))
 assert.match(job,/needs: \[validate-trigger, deploy, qa-main-functional-acceptance, qa-main-browser-acceptance\]/)
 assert.match(job,/E2E_MAIN_QA_SERVICE_KEY: \$\{\{ secrets\.MAIN_QA_SUPABASE_SECRET_KEY \}\}/)
 assert.match(job,/run: node scripts\/main-30-distinct-staff\.mjs/)
 assert.match(job,/if: always\(\)/)
 assert.match(job,/run: node scripts\/main-30-distinct-staff\.mjs --cleanup/)
 assert.match(job,/main-30-unique-staff-acceptance/)
 assert.doesNotMatch(job,/production|ci\.yml|deploy-cloudflare/i)
 assert.match(workflow,/qa-main-browser-acceptance, qa-main-functional-acceptance, qa-main-concurrency-acceptance/)
})
test('interrupted Main QA fixtures are recovered and verified before creating new test accounts',()=>{
 const job=workflow.slice(workflow.indexOf('  qa-main-concurrency-acceptance:'),workflow.indexOf('  qa-main-runtime-diagnostic:'))
 const recovery=job.indexOf('Recover prior interrupted Main test fixtures')
 const fresh=job.indexOf('Verify thirty distinct Main staff sessions')
 assert.ok(recovery>=0&&fresh>recovery,'Old QA cleanup must be first and must abort fresh tests on failure')
 assert.match(job,/QA_RECOVERY_RUN_ID: '44142366396'/)
 assert.match(job,/timeout --signal=TERM --kill-after=5s 45s env GITHUB_RUN_ID=/)
 assert.match(job,/node scripts\/main-30-distinct-staff\.mjs --cleanup/)
 assert.match(job,/exit 1/)
 assert.match(job,/E2E_MAIN_QA_SUPABASE_URL: https:\/\/npbjrtiolqperdgljnhi\.supabase\.co/)
})
