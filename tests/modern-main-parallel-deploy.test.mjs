import test from "node:test"
import assert from "node:assert/strict"
import {readFileSync} from "node:fs"
const get=p=>readFileSync(p,"utf8")
test("actual modern Main QA config is a different static-first Worker using only QA RLS",()=>{
 const modern=JSON.parse(get("modern/wrangler.main-qa.jsonc"))
 const legacy=JSON.parse(get("wrangler.jsonc"))
 const production=get(".github/workflows/deploy-cloudflare.yml")
 assert.equal(modern.name,"uptilldawn-modern-main")
 assert.equal(legacy.name,"uptilldawn-crew")
 assert.equal(modern.workers_dev,true)
 assert.equal(modern.preview_urls,false)
 assert.equal(modern.vars.SUPABASE_URL,"https://npbjrtiolqperdgljnhi.supabase.co")
 assert.ok(modern.vars.SUPABASE_ANON_KEY.startsWith("sb_publishable_"))
 assert.equal(modern.vars.UPT_MIGRATION_OAUTH_ENABLED,"false")
 assert.equal(modern.vars.UPT_MIGRATION_SCANNING_ENABLED,"false")
 assert.deepEqual(modern.assets.run_worker_first,["/api/*"])
 assert.equal(modern.assets.not_found_handling,"single-page-application")
 assert.ok(!JSON.stringify(modern).includes("eakoavcieossazqzplke"))
 for(const key of ["SERVICE_ROLE","API_TOKEN","ENCRYPTION_KEY","CLIENT_SECRET"])
  assert.ok(!JSON.stringify(modern).includes(key))
 assert.ok(production.includes("workflow_dispatch"))
 assert.ok(!production.includes("on:\n  push:"))
})
test("the existing Main workflow performs TWO isolated deployments on separate runners",()=>{
 const yml=get(".github/workflows/deploy-main.yml")
 assert.ok(yml.includes("  deploy-modern-main-qa:"))
 assert.ok(yml.includes("  qa-modern-main-qa:"))
 assert.ok(yml.includes("    needs: [validate-trigger, deploy-modern-main-qa]"))
 assert.ok(yml.includes("  deploy:\n"))
 assert.ok(yml.includes("if: needs.validate-trigger.outputs.eligible == 'true'"))
 assert.ok(yml.includes("npx wrangler deploy --config wrangler.main-qa.jsonc"))
 assert.ok(yml.includes("node modern/scripts/main-qa-live-smoke.mjs"))
 assert.ok(yml.includes("E2E_MAIN_MODERN_QA_ORIGIN: https://uptilldawn-modern-main.uptilldawn.workers.dev"))
 assert.ok(yml.includes("VITE_MIGRATION_ALLOW_WRITES: 'false'"))
 assert.ok(yml.includes("VITE_MIGRATION_SCANNING_ENABLED: 'false'"))
 assert.ok(yml.includes("workflow_run.head_sha"))
 assert.ok(!yml.includes("UPT_MIGRATION_SCANNING_ENABLED: 'true'"))
 assert.ok(!yml.includes("VITE_MIGRATION_ALLOW_WRITES: 'true'"))
})
