import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(path,'utf8')
test('Admin overview exposes no duplicate shortcuts, AI widget or central management hub',()=>{
 const dashboard=read('app/(app)/admin/page.tsx')
 const legacy=read('app/(app)/admin/management/page.tsx')
 const leadership=read('app/(app)/admin/management/leadership/page.tsx')
 assert.doesNotMatch(dashboard,/href="\/admin\/management"/)
 assert.doesNotMatch(dashboard,/href="\/admin\/time-records"/)
 assert.doesNotMatch(dashboard,/href="\/chat"/)
 assert.doesNotMatch(dashboard,/<PlatformAiAssistant\s*\/>/)
 assert.match(legacy,/redirect\('\/admin'\)/)
 assert.match(leadership,/redirect\('\/personnel'\)/)
})
test('Approvals owns the only leadership and personnel role selector',()=>{
 const approvals=read('app/(app)/personnel/page.tsx')
 const crew=read('app/(app)/crew/page.tsx')
 const editor=read('components/admin/personnel-two-role-editor.tsx')
 assert.match(approvals,/PersonnelTwoRoleEditor/)
 assert.doesNotMatch(crew,/PersonnelPortalRoles/)
 assert.doesNotMatch(crew,/form action=\{setPersonnelRole\}/)
 assert.match(editor,/roleLabels/)
 assert.match(editor,/name="role_one"/)
 assert.match(editor,/name="role_two"/)
 assert.match(editor,/value="none"/)
})
test('Tasks is the only Admin navigation entry for event and promotion task modules',()=>{
 const tasks=read('app/(app)/tasks/page.tsx')
 assert.match(tasks,/Evenementtaken beheren/)
 assert.match(tasks,/Promotietaken beheren/)
 const moderation=read('app/(app)/portals/administration/promotion-discipline/page.tsx')
 assert.ok(moderation.includes('actor.realIsAdmin'))
 const adminRoute=read('app/(app)/admin/management/promotion-discipline/page.tsx')
 assert.match(adminRoute,/export default PromotionDisciplinePage/)
})
