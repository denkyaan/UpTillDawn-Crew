import {assertOriginalSourceRoutes} from './helpers/modern-original-source-contract.mjs'
import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(path,'utf8')

test('task status and confirmations only use audited owner-scoped RPCs and are OFF by default',()=>{
 const actions=read('modern/src/lib/operational-writes.ts')
 const tasks=read('modern/src/screens/tasks.tsx')
 const queries=read('modern/src/lib/queries.ts')
 assert.ok(actions.includes('VITE_MIGRATION_ALLOW_WRITES==="true"'))
 assert.ok(actions.includes('rpc("upt_current_session_context")'))
 assert.ok(actions.includes('identity.id!==session.user.id'))
 assert.ok(actions.includes('rpc("upt_confirm_task_assignment",{p_assignment:assignmentId})'))
 assert.ok(actions.includes('rpc("upt_update_task_status",{p_assignment:assignmentId,p_status:status})'))
 assert.ok(!actions.includes('.from("task_assignments").update('))
 assert.ok(tasks.includes('MIGRATION_WRITES_ENABLED&&'))
 assert.ok(queries.includes('select("id,status,confirmed_at,tasks(id,title,description,event_id)")'))
})

test('chat uses RLS-authenticated bounded reads, one scoped live subscription, and read-only default',()=>{
 const chat=read('modern/src/screens/chats.tsx')
 const messages=read('modern/src/lib/chat-messages.ts')
 const actions=read('modern/src/lib/operational-writes.ts')
 assert.ok(messages.includes('.from("messages")'))
 assert.ok(messages.includes('.limit(100).abortSignal(signal)'))
 assert.ok(messages.includes('.eq("channel_id",channelId)'))
 assert.ok(chat.includes('.on("postgres_changes"'))
 assert.ok(chat.includes('filter:"channel_id=eq."+channelId'))
 assert.ok(chat.includes('void db.removeChannel(channel)'))
 assert.ok(chat.includes('timer.current=setTimeout'))
 assert.ok(chat.includes('setTimeout(()=>next.abort(),12000)'))
 assert.ok(chat.includes('if(!MIGRATION_WRITES_ENABLED)return'))
 assert.ok(actions.includes('rpc("upt_mark_chat_read",{p_channel:channelId})'))
 assert.ok(!messages.includes('service_role'))
})

test('offline chat uses a user scoped bounded outbox, stable operation ID and explicit no-delivery status',()=>{
 const outbox=read('modern/src/lib/chat-outbox.ts')
 const actions=read('modern/src/lib/operational-writes.ts')
 const chat=read('modern/src/screens/chats.tsx')
 assert.ok(outbox.includes('MAX_PER_USER=50'))
 assert.ok(outbox.includes('EXPIRES_MS=7*86400_000'))
 assert.ok(outbox.includes('crypto.randomUUID()'))
 assert.ok(outbox.includes('await sendOwnChatMessage({operationId:item.id,channelId:item.channelId,body:item.body})'))
 assert.ok(outbox.includes('if(user?.id!==uid)throw new Error("offline_user_mismatch")'))
 assert.ok(outbox.includes('if(current.uid!==uid)throw new Error("offline_user_mismatch")'))
 assert.ok(outbox.includes('for(const stale of all.filter'))
 assert.ok(outbox.includes('break // bound backend load and preserve FIFO'))
 assert.ok(actions.includes('rpc("upt_send_chat_message_operation_v2"'))
 assert.ok(actions.includes('p_operation:input.operationId'))
 assert.ok(chat.includes('const l=chatCopy(locale)'))
 assert.ok(chat.includes('setStatus(thisSent?l.sent:l.queued)'))
 assert.ok(chat.includes('const thisSent=!remaining.some(item=>item.id===queuedItem.id)'))
 assert.ok(chat.includes('setStatus(l.accountFailed)'))
 assert.ok(!outbox.includes('localStorage.'))
})

test('offline data and outbox never bleed across identities or remain visible after authorization loss',()=>{
 const session=read('modern/src/lib/session.tsx')
 const cache=read('modern/src/lib/use-read.ts')
 assert.ok(session.includes('purgeLocalUser(session.user.id)'))
 assert.ok(session.includes('purgeLocalUser(lastIdentity.current)'))
 assert.ok(session.includes('if(uid)await purgeLocalUser(uid)'))
 assert.ok(session.includes('import("./chat-outbox").then(m=>m.purgeOutboxUser(uid))'))
 assert.ok(cache.includes('const scope=uid+":"+kind'))
 assert.ok(cache.includes('const visible=state.scope===scope?state'))
 assert.ok(cache.includes('current.scope===scope'))
 assert.ok(!session.includes('import {purgeOutboxUser}'))
})

test('source reuse alone cannot unlock production or certify complete chat acceptance',()=>{
 assertOriginalSourceRoutes()
 assert.ok(read('modern/scripts/inventory.mjs').includes('verifiedPages:0'))
 assert.ok(read('modern/scripts/login-cutover-gate.mjs').includes('loginCutoverAllowed:false'))
})
