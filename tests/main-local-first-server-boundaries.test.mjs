import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=path=>readFileSync(path,'utf8')

test('global Next SSR never eagerly imports on-device translation and PWA/offline engines',()=>{
 const root=read('app/layout.tsx')
 const boundary=read('components/lazy-client-bootstraps.tsx')
 assert.match(root,/import \{ LazyPwaRegister, LazyLocaleSync \} from '@\/components\/lazy-client-bootstraps'/)
 assert.match(root,/<LazyPwaRegister \/>/)
 assert.match(root,/<LazyLocaleSync \/>/)
 assert.ok(root.indexOf('{children}')<root.indexOf('<LazyLocaleSync />'),'Translation must mount after children hydration')
 assert.doesNotMatch(root,/import\s+\{\s*(?:LocaleSync|PwaRegister)\s*\}\s+from/)
 assert.doesNotMatch(root,/ui-translation-runtime|crew-queue|global-offline-content-sync|tesseract|local-document-ocr/)
 assert.match(boundary,/^"use client"/)
 assert.equal((boundary.match(/\{ssr:false\}/g)||[]).length,2)
 assert.match(boundary,/import\("@\/components\/locale-sync"\)\.then\(module=>module\.LocaleSync\)/)
 assert.match(boundary,/import\("@\/components\/pwa-register"\)\.then\(module=>module\.PwaRegister\)/)
 assert.match(boundary,/<ClientLocaleSync\/>/)
 assert.match(boundary,/<ClientPwaRegister\/>/)
})
test('translation remains fully local and device-selected in four languages',()=>{
 const translation=read('components/locale-sync.tsx')
 const locale=read('lib/locale-preferences.ts')
 assert.match(translation,/import \{ translateRuntimeUi \} from/)
 assert.match(translation,/document\.documentElement\.lang = locale/)
 assert.match(translation,/LANGUAGE_APPLIED_EVENT/)
 assert.match(locale,/\['nl','fr','en','de'\]/)
 assert.match(locale,/return deviceUiLocale\(\)/)
})
test('PWA registration, background sync and OCR continue on the device',()=>{
 const pwa=read('components/pwa-register.tsx')
 const offline=read('components/crew/global-offline-content-sync.tsx')
 const ocr=read('components/administration/local-document-ocr-preview.tsx')
 const sw=read('public/sw.js')
 assert.match(pwa,/serviceWorker\.register\("\/sw\.js"/)
 assert.match(pwa,/queuedUploads\(user\.id\)/)
 assert.match(pwa,/synchronize\(/)
 assert.match(offline,/saveOfflineBrowseData/)
 assert.match(offline,/saveOfflineGuestlistAndSales/)
 assert.match(ocr,/recognizeLocally\(/)
 assert.doesNotMatch(ocr,/CLOUDMERSIVE_OCR_API_KEY|api\.cloudmersive\.com/)
 assert.match(sw,/LOCAL_OCR_CACHE/)
})
test('client-side rendering does not weaken server authorizations or cache RLS data globally',()=>{
 const authenticated=read('app/(app)/layout.tsx')
 const finance=read('app/(app)/portals/administration/finance/page.tsx')
 const server=read('lib/supabase/crew-server.ts')
 const worker=read('open-next.config.ts')
 const monitor=read('scripts/main-worker-outcomes.mjs')
 assert.match(authenticated,/await getCurrentUser\(\)/)
 assert.match(finance,/currentPortalAssignments\(\)/)
 assert.match(finance,/!canOpenPortal\('administration'/)
 assert.match(server,/const createRequestClient = cache\(async \(\) =>/)
 assert.match(worker,/enableCacheInterception: false/)
 assert.match(monitor,/process\.exitCode=1/)
})
