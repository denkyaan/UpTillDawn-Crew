import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const migration=read('supabase/migrations/20261109143414_role_scoped_standard_chats.sql')

test('three fixed shared chats are unique and legacy events channel retains history',()=>{
 for(const name of ['Algemene chat evenementen','Algemene chat promotie','Admin · Administratie'])
  assert.ok(migration.includes(name),name)
 assert.match(migration,/update public\.chat_channels set name='Algemene chat evenementen'/)
 assert.match(migration,/create unique index if not exists upt_chat_unique_standard_organization/)
 assert.match(migration,/on conflict \(id\) do nothing/)
 assert.match(migration,/public\.promotion_chat_messages old/)
 assert.match(migration,/old\.reply_to_message_id/)
 assert.doesNotMatch(migration,/drop table public\.promotion_chat_messages/i)
 assert.doesNotMatch(migration,/delete from public\.messages/i)
})
test('organization chat membership is enforced by database, not the portal UI',()=>{
 assert.match(migration,/create or replace function upt_private\.chat_standard_allowed\(p_channel uuid,p_user uuid\)/)
 assert.match(migration,/revoke all on function upt_private\.chat_standard_allowed\(uuid,uuid\) from public,anon,authenticated/)
 assert.match(migration,/c\.kind='organization' and upt_private\.chat_standard_allowed\(c\.id,\(select auth\.uid\(\)\)\)/)
 assert.match(migration,/p\.approved and not coalesce\(p\.account_blocked,false\)/)
 assert.match(migration,/rs\.role_one='administration'/)
 assert.match(migration,/rs\.role_one='promotion'/)
 assert.match(migration,/rs\.role_one in \('staff','responsible_lead'\)/)
 assert.match(migration,/a\.portal='administration'/)
 assert.match(migration,/a\.portal='promotion'/)
 assert.match(migration,/v_name='Algemene chat evenementen' and v_events/)
 assert.match(migration,/v_name='Algemene chat promotie' and v_promotion/)
 assert.match(migration,/v_name in[\s\S]*'Algemene chat evenementen','Algemene chat promotie','Admin · Administratie'/)
 assert.match(migration,/promotion_discipline/)
 assert.match(migration,/upt_private\.chat_standard_allowed\(c\.id,p\.id\)/)
 assert.match(migration,/upt_private\.chat_standard_allowed\(c\.id,s\.user_id\)/)
 assert.match(migration,/create or replace function upt_private\.notify_chat_message\(\)/i)
})
test('existing event and workplace-specific participation safeguards remain in place',()=>{
 for(const label of ["c.kind='event'","c.kind='workplace'","public.upt_is_responsible(c.event_id,c.workplace_id","from public.shifts s","s.user_id=(select auth.uid())"])
  assert.ok(migration.includes(label),label)
})
test('portal defaults and channel names are deterministic with no duplicate promotional group UI',()=>{
 const page=read('app/(app)/chat/page.tsx')
 const promo=read('app/(app)/portals/promotion/chats/page.tsx')
 const admin=read('app/(app)/portals/administration/chat/page.tsx')
 const client=read('components/crew/chat-client.tsx')
 assert.match(page,/channel\.name==='Algemene chat promotie'/)
 assert.match(page,/channel\.name==='Algemene chat evenementen'/)
 assert.match(page,/channel\.name==='Admin · Administratie'/)
 assert.match(page,/promotionOnly\?ordered\.find/)
 assert.match(page,/params\.administration==='1'\?ordered\.find/)
 assert.match(page,/chatBasePath=\{promotionOnly\?'/)
 assert.match(promo,/<SharedChatPage promotionOnly/)
 assert.doesNotMatch(promo,/<PromotionChatsClient/)
 assert.doesNotMatch(promo,/Aankondigingen|Announcements/)
 assert.match(admin,/administration:"1"/)
 assert.match(client,/chatBasePath\.startsWith\('\/portals\/administration'\)\?'Admin':'Administratie'/)
 assert.match(client,/channel\.name\|\|'Algemene chat evenementen'/)
})
